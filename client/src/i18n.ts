export type Ui = typeof sv

export function t(lang: Lang): Ui {
  return (lang === 'en' ? en : sv) as Ui
}

export function rememberLanguage(lang: Lang) {
  try {
    localStorage.setItem('yourtaskis-lang', lang)
  } catch {
    /* ignore */
  }
}

export function loadLanguage(): Lang {
  try {
    const v = localStorage.getItem('yourtaskis-lang')
    if (v === 'en' || v === 'sv') return v
  } catch {
    /* ignore */
  }
  return 'sv'
}

export function fill(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''))
}
